import type { SkillCategoryId } from "./master-profile.ts";

/**
 * Role presets select and reorder facts from the master profile. They never add facts.
 * `focus` lists canonical skill names or tags, most important first.
 */
export type RolePreset = {
  id: RoleId;
  label: string;
  tagline: string;
  focus: string[];
  categoryOrder: SkillCategoryId[];
  projectOrder: string[];
  /** Words in a job title or posting that suggest this role family. */
  signals: string[];
};

